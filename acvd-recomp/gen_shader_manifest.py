#!/usr/bin/env python3
"""
acvd-recomp/gen_shader_manifest.py
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
Generate data/acvd_shader_manifest.txt by scanning the ACVD disc's shader
files and recording their positions for the shader warm-up pipeline.

Usage:
    python gen_shader_manifest.py --disc <disc_root> --out <manifest.txt>
                                  [--prepared <dir>]

Arguments:
    --disc      PS3 disc root (directory that contains PS3_GAME/).
    --prepared  Optional ac4-prep output dir; when present, also scans for
                shader programs embedded in eboot.elf (rare; most are on disc).
    --out       Output manifest file (default: data/acvd_shader_manifest.txt).

The scanner looks for *.vpo and *.fpo files anywhere under PS3_GAME/USRDIR/
and records (source_idx, disc_rel_path, sha256) for each one.

The manifest format mirrors data/shader_manifest.txt:
    source <idx> disc  <rel_path>  <sha256>   # files on the disc
    source <idx> prepared <rel_path> <sha256> # files in the prepared dir
    vp <src_idx> <offset_hex> <len_hex> <start_slot>
    fp <src_idx> <offset_hex> <len_hex> <fp_env_hex>

NOTE: offset and length for whole-file shaders are always 0 and file_size.
      Embedded sub-file shaders (from eboot.elf) require --prepared and a
      separate scan step (not yet implemented; stub left for Stage 3).
"""

import argparse
import hashlib
import sys
from pathlib import Path

# Magic bytes that identify RSX vertex / fragment programs in raw binary blobs.
VP_MAGIC = b"\x47\x50\x55\x56"   # 'GPUV' — not standard; placeholder
FP_MAGIC = b"\x47\x50\x55\x46"   # 'GPUF' — not standard; placeholder

# Real RSX program files on PS3 have no universal magic; we identify them by
# extension only (.vpo = vertex program object, .fpo = fragment program object).
VP_EXT = {".vpo"}
FP_EXT = {".fpo"}


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def scan_disc(usrdir: Path) -> list[tuple[str, str, str]]:
    """
    Returns [(kind, rel_path_from_disc_root, sha256)] where kind = 'vp' or 'fp'.
    rel_path is relative to the disc root (e.g. 'PS3_GAME/USRDIR/shader/mdl/...vpo').
    """
    disc_root = usrdir.parent.parent  # PS3_GAME/../ = disc root
    results = []
    for p in sorted(usrdir.rglob("*")):
        if not p.is_file():
            continue
        ext = p.suffix.lower()
        if ext in VP_EXT:
            kind = "vp"
        elif ext in FP_EXT:
            kind = "fp"
        else:
            continue
        rel = p.relative_to(disc_root).as_posix()
        results.append((kind, rel, sha256_file(p)))
    return results


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--disc", required=True, type=Path, metavar="DIR",
                    help="PS3 disc root (contains PS3_GAME/)")
    ap.add_argument("--prepared", type=Path, metavar="DIR",
                    help="ac4-prep output directory (optional; for eboot-embedded shaders)")
    ap.add_argument("--out", type=Path, default=Path("data/acvd_shader_manifest.txt"), metavar="FILE",
                    help="output manifest path")
    args = ap.parse_args()

    disc: Path = args.disc
    out_path: Path = args.out

    usrdir = disc / "PS3_GAME" / "USRDIR"
    if not usrdir.is_dir():
        sys.exit(f"error: PS3_GAME/USRDIR not found under {disc}")

    print(f"scanning shaders under {usrdir} ...", file=sys.stderr)
    shaders = scan_disc(usrdir)
    if not shaders:
        sys.exit(f"error: no .vpo/.fpo files found under {usrdir}")
    print(f"found {len(shaders)} shader file(s)", file=sys.stderr)

    # Build source index (deduplicate by sha256 to avoid repeat entries).
    # In the original manifest each unique file path gets its own source index.
    path_to_idx: dict[str, int] = {}
    sources: list[tuple[str, str, str]] = []  # (kind_or_'disc', rel_path, sha256)
    for kind, rel, sha in shaders:
        if rel not in path_to_idx:
            idx = len(sources)
            path_to_idx[rel] = idx
            sources.append(("disc", rel, sha))

    # Write manifest.
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", newline="\n") as f:
        f.write("# ACVD native port: shader manifest v1 (generated by acvd-recomp/gen_shader_manifest.py).\n")
        f.write("# Positions only, no code: each line names a vertex (vp) or fragment (fp) program by the\n")
        f.write("# source file, offset and length (hex) of its bytes in the user's game files.\n")
        f.write("# ac4 --warm-shaders compiles them into the shader cache.\n")

        for idx, (loc, rel, sha) in enumerate(sources):
            f.write(f"source {idx} {loc} {rel} {sha}\n")

        # Emit one vp/fp line per shader using the whole file (offset=0, len=file_size).
        # start_slot (VP) and fp_env (FP) are unknown until the game runs; use 0 as placeholder.
        # Stage 3 will refine these from --dump-shaders output.
        for kind, rel, sha in shaders:
            src_idx = path_to_idx[rel]
            disc_path = disc / rel.replace("/", os.sep if sys.platform == "win32" else "/")
            try:
                file_len = disc_path.stat().st_size
            except OSError:
                file_len = 0
            if kind == "vp":
                # vp <src_idx> <offset_hex> <len_hex> <start_slot>
                f.write(f"vp {src_idx} 0 {file_len:x} 0\n")
            else:
                # fp <src_idx> <offset_hex> <len_hex> <fp_env_hex>
                f.write(f"fp {src_idx} 0 {file_len:x} 0\n")

    print(f"wrote {len(shaders)} shader entries ({sum(1 for k,*_ in shaders if k=='vp')} VP, "
          f"{sum(1 for k,*_ in shaders if k=='fp')} FP) to {out_path}", file=sys.stderr)
    print(f"manifest: {out_path}")


import os  # noqa: E402  (imported here to keep the top-level clean)

if __name__ == "__main__":
    main()
